/// 红绿灯读秒的**显示**状态机（纯逻辑，不依赖 Flutter，可直接单测）。
///
/// 移植自 cardesk 的 `core/nav/TrafficCountdown.kt`（那一版是用真车日志定下
/// 规则的），解决的是同一个问题：**每收到一帧就把读秒重锚回原始值**。
/// 而高德不是每秒都刷这个字段（真车帧间隔约 2 秒），原始值没变时重锚，等于
/// 把已经走掉的秒数又加回去 —— 读数在 `3 → 2 → 3` 之间来回跳，肉眼看就是
/// 「倒计时不准 / 比导航慢一秒」。
///
/// ## 规则
///
/// **同一个灯态里，读秒只减不增。**
///
/// - **灯态变了** → 重新起一轮，直接拿这一帧的原始读秒当锚点；
/// - **同一灯态**下：
///   - 原始读秒比当前显示**更小** → 供应商说「不多了」，以它为准重锚；
///   - 原始读秒**没变小**（多半是供应商没刷新）→ 沿用我们自己减出来的值，
///     **时钟原点不动**（挪了会把不足 1 秒的余量丢掉，数字越走越慢）；
///   - 我们自己的时钟**走到 0** → 停在 `0`（不猜灯态），等灯态变化或供应商
///     报新读数。供应商报的 `0` 一般不参与这个判断，见下一节。
///
/// ## 供应商报 0 是什么意思（2026-11-21 修）
///
/// **不是「还剩 0 秒」，而是「这一帧不给读数」。** 巡航通道在绿灯最后几秒
/// 会把 `countdown` 直接报成 0（真车日志里 14 个绿灯周期有 11 个以
/// `green@0` 收尾），而且会连着报好几帧。原来把 0 当归零处理，读秒当场
/// 钉死在 `0`，显示层据此画「黄环 + 0」—— 用户看到的就是「最后 3 秒一直是
/// 黄色 0」。真正的归零由本机时钟走到（[expiredAt]），不需要供应商宣布。
///
/// 但**读数从正数突然跳到 0**（`4 → 0`，中间 3、2、1 全被跳过）是另一种情况：
/// 这时供应商其实是在宣布「绿灯相位结束」，后面还有原车的 3 秒黄灯。真车
/// 日志（11-21 14:09:12 左转 `4 → 0`、14:02:12 左转 `17 → 0`）里这两次都是
/// 归零后**正好 3.0 秒**才换下一组信号。按「只是没读数」处理的话，本机时钟
/// 从 4 慢慢数，数到 2 那一包就把它换掉了 —— 用户看到的就是「黄 3、黄 2，
/// 然后整行消失」，永远见不到 1 和 0（2026-11-21 第二次报的问题）。
///
/// 所以：**绿灯的 fresh 0、且本机还显示 3 秒以上 → 压到 [amberLeadSeconds]
/// 重新起跑**，把黄灯 3 → 2 → 1 → 0 补完；本机已经在 3 秒以内时不压（读数
/// 正常走到 1、0 的周期里，压缩反而会让数字往回跳）。红灯报 0 一律不压。
///
/// ## 归零之后显示什么
///
/// 显示 `0`，**不画「—」**（2026-11-20 改）。原来归零就换成「—」，而绿灯
/// 最后 3 秒是「黄环 + 读秒」，一归零黄灯立刻变成「黄环 + —」，实车看着就是
/// 「变黄了但没有倒计时」（用户报的原话）。「—」只留给「这一轮压根没带读秒」，
/// 这两种情况在数据上本来就不是一回事（[expired] 区分）。
///
/// 归零之后如果供应商又报了一个**和上一帧不同**的读数，说明它改口了
/// （巡航换灯 / 换路口时灯色可能还是 `green`），以它为准重起一轮；同一读数
/// 重复推上来不复活，否则读数会在 `0` 和旧值之间来回闪。
///
/// 断档超过有效期时，调用方应先 [reset] 再 [accept]，否则「断档很久」会被
/// 当成「同一轮读秒的延续」（见 [lastAnchorAt]）。
///
/// ## 时刻
///
/// 所有时刻由调用方传入（毫秒，**单调递增**即可，绝对值不重要），内部不读
/// 系统时钟。这样和 UI 的重绘节拍解耦，也不用担心两端墙钟不一致。
class TrafficCountdown {
  /// 绿灯最后几秒按黄灯展示的秒数 —— 和显示层 `TrafficSignal.amberLeadSeconds`
  /// 是同一条规则（原车观感，用户 2026-11-14 定），这里用它是为了在供应商
  /// 突然宣布读秒结束时把黄灯补齐（见 [accept]）。
  static const int amberLeadSeconds = 3;

  /// 供应商宣布读秒结束时，把压到 [amberLeadSeconds] 的时钟原点再提前这么多：
  /// 黄灯 3、2、1 各占整秒，末尾的 `0` 还能露半秒（见 [accept]）。
  static const int _zeroTailMs = 500;

  /// 当前这一轮属于哪个灯态（null = 还没收到过信号）。
  String? _lamp;

  /// 锚点上的读秒（null = 这一轮没有读秒可显示）。
  int? _shown;

  /// 时钟原点（调用方的单调时钟，毫秒）：[_shown] 这个读数是从哪一刻开始走的。
  ///
  /// 只在「读数本身变了」的时候挪（新读数 / 灯态变化 / 供应商宣布结束），
  /// **同一读数重复推上来不挪** —— 否则每次重锚都把不足 1 秒的余量丢掉
  /// （`~/ 1000` 取整），帧间隔 1.5 秒时每个数字会多停半秒，整段黄灯能拖到
  /// 3.5 秒，末尾的 `0` 也就被挤到信号行消失之后了。
  int _anchorAt = 0;

  /// 最后一帧 [accept] 的时刻（毫秒）。TTL 判活用它（[lastAnchorAt]），
  /// 和时钟原点是两回事。
  int _lastFrameAt = 0;

  /// 这一轮读秒是否已经归零（归零后停在 0，直到灯态变化或供应商改口）。
  bool _expired = false;

  /// 上一帧供应商报的原始读数（含 0 / null）。
  ///
  /// 用来分辨「供应商改口」和「同一帧重复推」：只有改口才允许在归零之后
  /// 重起一轮，重复推同一帧不复活读数（否则会在 0 和旧值之间来回闪）。
  int? _lastRaw;

  /// 当前这一轮属于哪个灯态；null = 还没收到过信号。
  String? get lamp => _lamp;

  /// 这一轮读秒是否已经走完（归零后停在 `0`，不再画「—」）。用来区分
  /// 「归零」和「这一帧根本没带读秒」—— 前者是「绿灯结束」，要按黄灯画；
  /// 后者没有依据，保持绿灯。
  bool get expired => _expired;

  /// 是否已经有锚点（收到过至少一帧）。
  bool get anchored => _lamp != null;

  /// 上一次 [accept] 的时刻（毫秒）；还没收到过信号时返回 0。
  ///
  /// 用来判断「这一轮是不是断档了很久」——断档超过有效期就该重新起一轮，
  /// 而不是接着上一轮继续减。**注意不是时钟原点**：读数没变的帧不挪原点，
  /// 但这里必须跟着走，否则会误判成断档。
  int get lastAnchorAt => _lamp == null ? 0 : _lastFrameAt;

  /// 收到一帧信号：更新锚点。
  ///
  /// - [lamp] 本帧灯态（'red' / 'green' / 'amber' / 'unknown'）。
  /// - [raw] 本帧的原始读秒（null / `<= 0` 都算「这一帧没给读数」）。
  /// - [atMs] 调用方的单调时钟（毫秒）。
  ///
  /// 返回锚定之后的读秒（null = 这一轮压根没有读秒，`0` = 已经走完）。
  int? accept(String lamp, int? raw, int atMs) {
    // 0 和负数都当成「这一帧没给读数」，**不当成归零**：巡航绿灯最后几秒
    // 供应商就是这个行为（连着报 0），当真了读秒会提前钉死在 0，
    // 最后 3 秒就变成「黄环 + 0」。归零交给本机时钟走。
    final next = raw != null && raw > 0 ? raw : null;
    // 供应商这一次报的数和上一帧不一样 = 新信息，不是重复推送。
    final fresh = raw != _lastRaw;

    if (_lamp != lamp) {
      // 灯态变了 → 重新起一轮，这一帧的读数就是新锚点。
      _lamp = lamp;
      _shown = next;
      _expired = false;
      _anchorAt = atMs;
      _lastFrameAt = atMs;
      _lastRaw = raw;
      return _shown;
    }

    // 同一灯态：先按本机时钟算出「到这一刻该显示多少」。**只算不改**——
    // [_shown] / [_anchorAt] 记的是「上一次锚定的读数 + 它的原点」，
    // 每帧都往里写会把同一段时间重复扣掉（读数一蹦就归零）。
    final shownNow = _shown == null ? null : current(atMs);
    if (shownNow != null && shownNow <= 0) _expired = true;

    // 新时钟原点。**默认沿用旧原点**：读数没变的帧只说明「供应商没刷新」，
    // 重锚会把不足 1 秒的余量丢掉，数字越走越慢。只有读数真的变了才挪。
    var anchorAt = _anchorAt;

    if (_expired) {
      // 我们这边已经走到 0，但供应商给了一个**新**读数：它知道得更多
      // （巡航换灯 / 换路口时灯色可能还是 green），以它为准重起一轮。
      // 同一读数重复推上来不复活，否则读数会在 0 和旧值之间来回闪。
      if (next != null && fresh) {
        _shown = next;
        _expired = false;
        anchorAt = atMs;
      }
    } else if (next != null) {
      // 供应商的原始值只用来「往下压」，**不用来把秒数加回去**。
      if (shownNow == null || next < shownNow) {
        _shown = next;
        anchorAt = atMs;
      }
    } else if (fresh && raw != null) {
      // 这一帧报了个新的 0 / 负数（不是重复推 0）：供应商在宣布绿灯相位
      // 结束。我们自己的时钟要是还停在 3 秒以上（读数 `4 → 0` 这种跳变），
      // 就压到 [amberLeadSeconds] 重新起跑，把黄灯 3 → 2 → 1 → 0 补完；
      // 否则黄灯数到 2 就被下一包换掉，永远看不到 1、0。已经在 3 秒以内
      // 时不动，让数字按原样走到 0。
      //
      // 只管绿灯：黄灯序列是「绿 → 黄 → 红」的过渡，红灯读数归零时压到 3
      // 会把它正在跳的几十秒直接砍掉。
      if (lamp == 'green' && shownNow != null && shownNow > amberLeadSeconds) {
        _shown = amberLeadSeconds;
        // 时钟原点提前零点几秒：真车日志里这一行信号正好在宣布结束 3.0 秒
        // 后被换掉（14:09:12 左转），压到 3 秒起跑的话末尾的 0 一秒都露不
        // 出来，看起来又成了「数到 1 就没了」。提前 [_zeroTailMs] 让 3、2、1
        // 各占整秒、末尾的 0 有半秒可看。
        anchorAt = atMs - _zeroTailMs;
      }
    }

    _anchorAt = anchorAt;
    _lastFrameAt = atMs;
    _lastRaw = raw;
    return current(atMs);
  }

  /// 按当前时刻算显示值（**不推进状态**）。
  ///
  /// 返回显示用的读秒：`null` = 这一轮没有读秒（画「—」）；`0` = 已经走到
  /// 尽头（照常画数字 `0`，不换「—」）。
  int? current(int atMs) {
    final shown = _shown;
    if (shown == null) return null;
    final left = shown - (atMs - _anchorAt) ~/ 1000;
    return left > 0 ? left : 0;
  }

  /// 下一次读秒跳变的时刻（毫秒）；没有可显示的读秒时返回 null。
  ///
  /// 读秒在 `anchor + k*1000` 处跳变，返回第一个**大于** [atMs] 的。
  /// UI 用它排下一次重绘，比「按整秒轮询」准：锚点落在任意毫秒上，
  /// 跳变也跟着锚点走。归零之后不再跳变，交给 TTL 的节拍收尾。
  int? nextTickMs(int atMs) {
    final shown = _shown;
    if (shown == null || shown <= 0) return null;
    final since = atMs - _anchorAt;
    // 锚点在未来（`ageMs` 修正后可能落在「包成形那一刻」，比 now 早；
    // 但首帧的 `atMs` 也可能小于 0）—— 等锚点到了再算。
    if (since < 0) return _anchorAt;
    return _anchorAt + (since ~/ 1000 + 1) * 1000;
  }

  /// 按当前时刻判断这一轮读秒是否已经走完。
  ///
  /// 和 [expired] 不同：[expired] 只在 [accept] 时更新，而读数可能在两次
  /// 包之间自己走到 0。显示层判断「绿灯该不该转黄」要用这一个。
  bool expiredAt(int atMs) {
    if (_expired) return true;
    final shown = _shown;
    if (shown == null) return false;
    return shown - (atMs - _anchorAt) ~/ 1000 <= 0;
  }

  /// 清空（导航结束 / 信号断档）。
  void reset() {
    _lamp = null;
    _shown = null;
    _anchorAt = 0;
    _lastFrameAt = 0;
    _expired = false;
    _lastRaw = null;
  }
}
