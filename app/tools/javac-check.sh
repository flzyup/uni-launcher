#!/bin/bash
# Fast standalone compile check for the UNI Android Java sources.
#
# The full Gradle build has to resolve the whole Android toolchain and takes
# many minutes on a slow link; this compiles the same sources directly with
# javac against android.jar + flutter.jar + a few androidx stubs, which is
# enough to catch type and syntax errors in a second or two.
#
# Pass an SDK platform id to compile against a different API level:
#   ./tools/javac-check.sh 9     # android-9  = API 28，车机（Android 9）的级别
#   ./tools/javac-check.sh 24    # UNI 声明的 minSdk
#   ./tools/javac-check.sh 29
#
# Compiling against the head unit's own level (android-9 = API 28) is what
# catches NewApi violations: methods such as String.isBlank (API 35),
# String.join (API 26) or java.nio.file.Files (API 26) compile fine against
# android-36 and then throw NoSuchMethodError on the car.
#
# Note: at API 24 the whole project does not compile — existing business code
# uses API 26+ members (canRequestPackageInstalls, AudioPlaybackConfiguration,
# ...). The log/diagnostics package itself is clean at API 24; the pre-existing
# failures show up as errors in other files.
#
# Environment:
#   JAVA_HOME       JDK 17+ root (default: the platform's java_home)
#   ANDROID_SDK     SDK root (default: $ANDROID_HOME / $ANDROID_SDK_ROOT /
#                   the platform's usual location)
#   FLUTTER_ROOT    Flutter SDK root (default: ~/development/flutter)
set -u
APP="$(cd "$(dirname "$0")/.." && pwd)"
if [ -z "${JAVA_HOME:-}" ]; then
  JAVA_HOME="$(/usr/libexec/java_home 2>/dev/null || true)"
fi
if [ -z "${SDK:-}" ]; then
  for candidate in "${ANDROID_SDK:-}" "${ANDROID_HOME:-}" "${ANDROID_SDK_ROOT:-}" \
      "$HOME/Library/Android/sdk" "$HOME/Android/Sdk"; do
    if [ -n "$candidate" ] && [ -d "$candidate/platforms" ]; then SDK="$candidate"; break; fi
  done
fi
SDK="${SDK:?ANDROID_SDK not found: set ANDROID_SDK (or ANDROID_HOME / ANDROID_SDK_ROOT)}"
FLUTTER="${FLUTTER_ROOT:-$HOME/development/flutter}"
export JAVA_HOME
export PATH="$JAVA_HOME/bin:$PATH"

API="${1:-36}"
OUT=/tmp/uni-javac-$API
STUBS=/tmp/uni-stubs
rm -rf "$OUT" "$STUBS" && mkdir -p "$OUT" "$STUBS/androidx/lifecycle" "$STUBS/androidx/annotation"

# The Flutter embedding needs these two, and they come from AARs that are
# resolved by Gradle; stubs keep this check independent of the dependency
# cache.
cat > "$STUBS/androidx/lifecycle/LifecycleOwner.java" <<'EOF'
package androidx.lifecycle;
public interface LifecycleOwner {}
EOF
for annotation in Keep NonNull Nullable VisibleForTesting; do
cat > "$STUBS/androidx/annotation/$annotation.java" <<EOF
package androidx.annotation;
public @interface $annotation {}
EOF
done

# MediaStore.Downloads 是 API 29 才有的类。Diagnostics 只在 SDK_INT >= 29 的
# 分支里用它（API 28 走直接写文件那条路），所以运行时是安全的；但按 API 28
# 编译时整包会因为找不到这个类而编不过，那个级别的检查就废了。
#
# 这里用一份只含 Downloads 的 MediaStore 桩顶掉 android.jar 里的那份：显式
# 参与编译的源文件会遮蔽 classpath 里的同名类，桩里的列名与官方常量一致，
# 不影响被检查的代码。
if [ "$API" -lt 29 ]; then
mkdir -p "$STUBS/android/provider"
cat > "$STUBS/android/provider/MediaStore.java" <<'EOF'
package android.provider;
/** 仅用于 javac-check：补上 API 29 才有的 MediaStore.Downloads。 */
public class MediaStore {
    public static final class Downloads {
        public static final android.net.Uri EXTERNAL_CONTENT_URI = null;
        public static final String _ID = "_id";
        public static final String DISPLAY_NAME = "_display_name";
        public static final String RELATIVE_PATH = "relative_path";
        public static final String MIME_TYPE = "mime_type";
        public static final String IS_PENDING = "is_pending";
    }
    /** MediaStore.Files / MediaColumns 是 API 1 就有的，这里原样列出。 */
    public static final class Files {
        public static android.net.Uri getContentUri(String volumeName) { return null; }
    }
    public interface MediaColumns {
        String _ID = "_id";
        String DATA = "_data";
        String DISPLAY_NAME = "_display_name";
        String MIME_TYPE = "mime_type";
        String SIZE = "_size";
    }
}
EOF
fi

CP="$SDK/platforms/android-$API/android.jar"
CP="$CP:$FLUTTER/bin/cache/artifacts/engine/android-arm64/flutter.jar"
CP="$CP:$APP/build/app/intermediates/compile_r_class_jar/debug/generateDebugRFile/R.jar"

# The unit tests need JUnit; take it from the dependency cache when it is
# already there so the test sources are type-checked as well.
JUNIT=$(find "${GRADLE_USER_HOME:-$HOME/.gradle}" -name "junit-4.13.2.jar" 2>/dev/null | head -1)
if [ -n "$JUNIT" ]; then
    CP="$CP:$JUNIT"
fi

# The plugin registrant is generated by the Flutter tool and pulls in the
# integration-test plugin, which is not on this classpath.
find "$APP/android/app/src/main/java" -name "*.java" \
    ! -name "GeneratedPluginRegistrant.java" > /tmp/uni-srcs.txt
find "$APP/android/app/src/test/java" -name "*.java" >> /tmp/uni-srcs.txt
find "$APP/build/app/generated/source/buildConfig/debug" -name "BuildConfig.java" >> /tmp/uni-srcs.txt
find "$STUBS" -name "*.java" >> /tmp/uni-srcs.txt

javac -nowarn -proc:none -d "$OUT" -cp "$CP" @/tmp/uni-srcs.txt 2>&1 | grep -v "^Note:" | head -60
